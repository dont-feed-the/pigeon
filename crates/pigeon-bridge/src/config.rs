//! Bridge configuration: local portal accounts point at their own control
//! daemons. A public origin is explicit; proxy headers never choose redirects,
//! cookies, or credential endpoints. HTTP is permitted only on loopback.

use std::collections::BTreeMap;
use std::net::SocketAddr;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use url::Url;

#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
/// Explicit listener, peer storage, and portal accounts.
pub struct Config {
    /// Local HTTP listener; terminate public TLS at a reverse proxy.
    pub listen: SocketAddr,
    /// Canonical HTTPS origin, or loopback HTTP for development.
    pub public_url: String,
    /// Private persistent client homes, credentials, and DAV metadata.
    pub state_dir: PathBuf,
    #[serde(default)]
    /// Shared immutable content; defaults to `state_dir/content`.
    pub content_dir: Option<PathBuf>,
    /// Absolute path to the matching `pigeond` executable.
    pub pigeond: PathBuf,
    #[serde(default = "max_upload")]
    /// Maximum complete file size and pending chunk budget per client.
    pub max_upload_bytes: u64,
    #[serde(default = "max_clients")]
    /// Maximum number of active independently authorized clients per person.
    pub max_clients_per_user: usize,
    #[serde(default = "network")]
    /// `n0` for normal Pigeon networking; `off` for loopback-only development.
    pub peer_network: String,
    /// Portal user names and their existing personal control peers.
    pub users: BTreeMap<String, User>,
}

#[derive(Clone, Deserialize)]
#[serde(deny_unknown_fields)]
/// A person authenticating to the portal, independently of app credentials.
pub struct User {
    /// Argon2id hash generated by `pigeon-bridge hash-password`.
    pub password_hash: String,
    /// An existing daemon of this person; its default group is exposed.
    pub control_socket: PathBuf,
    #[serde(default)]
    /// Existing content node; defaults to the control peer, or use a custodian.
    pub storage_socket: Option<PathBuf>,
}

fn max_upload() -> u64 {
    10 * 1024 * 1024 * 1024
}
fn max_clients() -> usize {
    20
}
fn network() -> String {
    "n0".into()
}

impl Config {
    /// The shared content pool used by every managed client peer.
    pub fn content_dir(&self) -> PathBuf {
        self.content_dir
            .clone()
            .unwrap_or_else(|| self.state_dir.join("content"))
    }

    /// Reads a configuration and validates paths, accounts, and public origin.
    pub fn load(path: &Path) -> Result<Self, String> {
        let text = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
        let mut config: Self = toml_edit::de::from_str(&text).map_err(|e| e.to_string())?;
        config.public_url = config.public_url.trim_end_matches('/').to_owned();
        config.validate()?;
        Ok(config)
    }

    /// Parses the configured canonical public origin.
    pub fn origin(&self) -> Result<Url, String> {
        Url::parse(&self.public_url).map_err(|e| e.to_string())
    }

    /// Refuses ambiguous origins, unsafe HTTP bindings, and invalid accounts.
    pub fn validate(&self) -> Result<(), String> {
        let url = self.origin()?;
        if url.path() != "/"
            || url.query().is_some()
            || url.fragment().is_some()
            || !url.username().is_empty()
            || url.password().is_some()
        {
            return Err("public_url must be an origin, without a path or credentials".into());
        }
        let local = matches!(
            url.host_str(),
            Some("localhost" | "127.0.0.1" | "[::1]" | "::1")
        );
        if url.scheme() != "https"
            && !(url.scheme() == "http" && local && self.listen.ip().is_loopback())
        {
            return Err(
                "Use HTTPS for public_url, or bind HTTP to loopback for development".into(),
            );
        }
        if !self.state_dir.is_absolute()
            || !self.pigeond.is_absolute()
            || !self.content_dir().is_absolute()
        {
            return Err("state_dir, content_dir and pigeond must be absolute paths".into());
        }
        if self.content_dir().starts_with(self.state_dir.join("peers")) {
            return Err("content_dir must be outside managed client homes".into());
        }
        if self
            .state_dir
            .join("run")
            .join("0".repeat(32) + ".sock")
            .as_os_str()
            .len()
            > 100
        {
            return Err("state_dir is too long for portable Unix socket paths".into());
        }
        if self.max_clients_per_user == 0 || self.max_upload_bytes == 0 || self.users.is_empty() {
            return Err("Configure at least one user and positive upload/client limits".into());
        }
        if self.peer_network != "n0" && self.peer_network != "off" {
            return Err("peer_network must be n0 or off".into());
        }
        for (name, user) in &self.users {
            if name.is_empty()
                || name.len() > 80
                || !name
                    .bytes()
                    .all(|b| b.is_ascii_alphanumeric() || b"_.-".contains(&b))
            {
                return Err("User names must contain only ASCII letters, digits, _, . or -".into());
            }
            if !user.control_socket.is_absolute()
                || user
                    .storage_socket
                    .as_ref()
                    .is_some_and(|p| !p.is_absolute())
                || !user.password_hash.starts_with("$argon2id$")
                || argon2::PasswordHash::new(&user.password_hash).is_err()
            {
                return Err(format!(
                    "{name}: use an absolute control_socket and an Argon2id password hash"
                ));
            }
        }
        Ok(())
    }
}
